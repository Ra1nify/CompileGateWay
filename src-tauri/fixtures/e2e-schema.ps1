# End-to-end fixture for JSON Schema (design doc §2).
#
# Covers: CLI surface (`cgw schema [name]` / `cgw manifests schema` -> five schemas, and a
# misspelled name is blocked before the request); real data (one project holding all **seven
# task types**, validated with ajv by `mcp/test/schema.mjs`); save-time validation (empty batch /
# empty taskId must be rejected by the API instead of being dropped silently).
#
# Fully offline: client points at 127.0.0.1:1 (never connects); it only saves, never runs.
# USERPROFILE points into the sandbox, so the user's ~/CompileGateway is untouched.
#
# Usage: cd src-tauri; pwsh -NoProfile -File fixtures\e2e-schema.ps1

$ErrorActionPreference = 'Stop'
$root = Join-Path $env:TEMP 'cgw-schema'
$rel = 'F:\CODEX\CompileGateWay\src-tauri\target\release'
$repo = 'F:\CODEX\CompileGateWay'

Remove-Item $root -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $root, "$root\home", "$root\src" | Out-Null
Copy-Item "$rel\compilegateway-daemon.exe" $root
Copy-Item "$rel\compilegateway-cli.exe" $root
Set-Content "$root\config.json" '{ "port": 0, "language": "zh-Hans", "listen": "lan", "logRetainDays": 7 }' -Encoding utf8

$env:USERPROFILE = "$root\home"
$daemon = Start-Process -FilePath "$root\compilegateway-daemon.exe" -WorkingDirectory $root -PassThru -WindowStyle Hidden
$url = $null
for ($i = 0; $i -lt 60; $i++) {
  Start-Sleep -Milliseconds 250
  if (Test-Path "$root\runtime.json") {
    try { $url = (Get-Content "$root\runtime.json" -Raw | ConvertFrom-Json).url } catch { }
    if ($url) { break }
  }
}
if (-not $url) { throw 'daemon did not start' }
$cgw = "$root\compilegateway-cli.exe"
Write-Host "daemon: $url"

$bad = 0
function Expect($cond, $what, $detail) { if ($cond) { Write-Host "  ok   $what" } else { Write-Host "  FAIL $what  $detail"; $script:bad++ } }

# ---------------------------------------------------------------- create project + seven tasks
& $cgw clients add --host 127.0.0.1 --port 1 --user x --password y --name offline --url $url | Out-Null
$clients = (& $cgw clients list --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$clientId = $clients.clients[0].id
# Design doc §6.1: browse / project registration / build-type probing **share one root whitelist**.
# Acceptance record §7 caught exactly "browse says no, registration says yes" -- now they agree:
# the temp dir is not whitelisted, so registration **is rejected** and the error says what to do.
New-Item -ItemType Directory -Force -Path "$root\src" | Out-Null
$denied = (& $cgw projects add --client $clientId --path "$root\src" --name 被拒的 --url $url 2>&1 | Out-String)
Expect ($LASTEXITCODE -ne 0 -and $denied -match 'allowedRoots') 'directory outside the whitelist rejected (same check as browse)' $denied
& $cgw config set --allowed-roots "$root" --url $url | Out-Null
& $cgw projects add --client $clientId --path "$root\src" --name schema --url $url | Out-Null
$projects = (& $cgw projects --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$projectId = $projects.projects[0].id
Write-Host "project $projectId / client $clientId"

$tasks = [ordered]@{
  't-build'  = @{ kind = 'build';  name = '构建';  manifest = 'xcode'; variables = @{ scheme = 'Runner' } }
  't-push'   = @{ kind = 'push';   name = '推送';  clean = $true }
  't-pull'   = @{ kind = 'pull';   name = '拉取';  sources = @(@{ side = 'host'; path = 'src' }); to = @{ side = 'host'; path = 'back' } }
  't-copy'   = @{ kind = 'copy';   name = '复制';  from = @{ side = 'host'; path = 'src' }; to = @{ side = 'host'; path = 'out' } }
  't-move'   = @{
    kind = 'move'; name = '剪切'
    from = @{ side = 'host'; path = '{{inputs.source}}' }
    to   = @{ side = 'host'; path = '{{inputs.dest}}' }
    # Input/output contract (design doc §7.6.3 / §7.6.4): save-time validation and ajv must both
    # handle these two blocks. This task is never run by a batch (only saved to check the schema),
    # so declaring outputs has no side effect.
    inputs = @{
      source = @{ type = 'path'; side = 'host' }
      dest   = @{ type = 'path'; side = 'host'; default = 'out/a' }
    }
    outputs = @{
      moved = @{ type = 'file'; side = 'host'; path = '{{inputs.dest}}'; required = $false }
    }
  }
  't-delete' = @{ kind = 'delete'; name = '删除';  target = @{ side = 'host'; path = 'out' } }
  't-export' = @{ kind = 'export'; name = '导出';  sources = @(@{ side = 'host'; path = 'src' }); outputName = 'x.zip' }
}
$saved = @()
foreach ($id in $tasks.Keys) {
  $body = ($tasks[$id] | ConvertTo-Json -Depth 8 -Compress)
  $out = (& $cgw tasks save $projectId --body $body --url $url 2>&1 | Out-String)
  if ($LASTEXITCODE -ne 0) { Write-Host "!! failed to save ${id}: $out"; $bad++ } else { $saved += $id }
}
Write-Host "saved tasks: $($saved -join ', ')"

# When creating a task the id is **generated by the server** (an id in the request only selects an
# existing task to overwrite), so the real ids are fetched back by kind here for the batches below.
$listed = (& $cgw tasks $projectId --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$byKind = @{}
foreach ($task in $listed) { $byKind[$task.kind] = $task.id }
Write-Host "ids fetched by kind: $(($byKind.GetEnumerator() | Sort-Object Name | ForEach-Object { "$($_.Key)=$($_.Value)" }) -join ' ')"
Expect ($byKind.Count -eq 7) "all seven task types saved" "actual $($byKind.Count) kinds"

# ---------------------------------------------------------------- CLI surface
Write-Host "`n--- cgw schema ---"
$names = (& $cgw schema --url $url 2>&1) -join ' '
$expectedNames = 'manifest', 'task', 'batch', 'client', 'project', 'workflow'
$missingNames = $expectedNames | Where-Object { $names -notmatch $_ }
Expect ($missingNames.Count -eq 0) 'cgw schema lists all six names' ($missingNames -join ',')

$taskSchema = (& $cgw schema task --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($taskSchema.'$schema' -eq 'http://json-schema.org/draft-07/schema#') 'task schema is draft-07'
Expect ($taskSchema.oneOf.Count -eq 7) 'task schema has 7 oneOf branches'

$viaManifests = (& $cgw manifests schema --url $url 2>&1 | Out-String)
$viaSchema = (& $cgw schema manifest --url $url 2>&1 | Out-String)
Expect ($viaManifests -eq $viaSchema) 'manifests schema and schema manifest are equivalent'

$out = (& $cgw schema nope --url $url 2>&1 | Out-String)
Expect ($LASTEXITCODE -eq 1 -and $out -match '没有这份 schema') 'misspelled name blocked (exit code 1)'

# ---------------------------------------------------------------- save-time validation
Write-Host "`n--- batch validation ---"
function SaveBatch($json) {
  $out = (& $cgw batch save $projectId --body $json --url $url 2>&1 | Out-String)
  return @{ code = $LASTEXITCODE; out = $out }
}
$r = SaveBatch '{"name":"空","steps":[]}'
Expect ($r.code -eq 3 -and $r.out -match '至少要有一个步骤') 'empty batch rejected (exit code 3)' $r.out
$r = SaveBatch '{"name":"空步骤","steps":[{"taskId":""}]}'
Expect ($r.code -eq 3 -and $r.out -match 'taskId 不能为空') 'empty taskId rejected (exit code 3)' $r.out
$r = SaveBatch '{"name":"不存在的任务","steps":[{"taskId":"t-nope"}]}'
Expect ($r.code -eq 3 -and $r.out -match '步骤引用的任务不存在') 'reference to a missing task rejected (exit code 3)' $r.out

# Step id and step output reference (design doc §7.6.5): these must be caught at **save time**,
# not only when a run discovers the reference cannot be resolved.
$r = SaveBatch (@{ name = '重名'; steps = @(
      @{ id = 'a'; taskId = $byKind['copy'] }, @{ id = 'a'; taskId = $byKind['move'] }) } |
    ConvertTo-Json -Depth 6 -Compress)
Expect ($r.code -eq 3 -and $r.out -match '步骤 id 重复') 'duplicate step id rejected (exit code 3)' $r.out

$r = SaveBatch (@{ name = '前向引用'; steps = @(
      @{ id = 'a'; taskId = $byKind['copy']; variables = @{ x = '{{steps.b.outputs.moved}}' } },
      @{ id = 'b'; taskId = $byKind['move'] }) } |
    ConvertTo-Json -Depth 6 -Compress)
Expect ($r.code -eq 3 -and $r.out -match '后面的步骤') 'reference to a later step rejected (exit code 3)' $r.out

$r = SaveBatch (@{ name = '没这个输出'; steps = @(
      @{ id = 'a'; taskId = $byKind['copy'] },
      @{ id = 'b'; taskId = $byKind['move']; variables = @{ x = '{{steps.a.outputs.nope}}' } }) } |
    ConvertTo-Json -Depth 6 -Compress)
Expect ($r.code -eq 3 -and $r.out -match '没有声明的输出') 'reference to an undeclared output rejected (exit code 3)' $r.out
$validBatch = (@{
    name  = '全流程'
    steps = @(@{ taskId = $byKind['copy'] }, @{ taskId = $byKind['export'] })
  } | ConvertTo-Json -Depth 6 -Compress)
$r = SaveBatch $validBatch
Expect ($r.code -eq 0) 'a normal batch saves fine' $r.out

# Step-level variables (design doc §7.3): the WebUI form could not set them (it only sent taskId),
# and now there is a JSON entry point -- this pins the API half: writable and readable back.
$withVars = (@{
    name  = '带步骤变量'
    steps = @(@{ taskId = $byKind['build']; variables = @{ scheme = 'Runner'; configuration = 'Debug' } })
  } | ConvertTo-Json -Depth 6 -Compress)
$r = SaveBatch $withVars
Expect ($r.code -eq 0) 'batch with step-level variables saves fine' $r.out
$allBatches = (& $cgw batches $projectId --json --url $url 2>&1 | Out-String)
# Note: `cgw batches --json` prints an **array** (same as `cgw tasks --json`),
# not `{batches:[...]}` -- that is what the MCP tools return.
$savedBatch = (($allBatches | ConvertFrom-Json) | Where-Object { $_.name -eq '带步骤变量' })
Expect ($savedBatch -and $savedBatch.steps[0].variables.scheme -eq 'Runner') 'step-level variables read back' $allBatches

# ---------------------------------------------------------------- GET / PATCH (design doc §10.1)
# The resource model in the design doc includes `GET` (list) and `PATCH` (change only the given
# fields); previously there was only `POST` (whole-record replace) + `DELETE`, so renaming meant
# resending the whole task and any omitted field silently fell back to its default.
Write-Host "`n--- GET / PATCH ---"
$taskList = (& $cgw api GET "/api/projects/$projectId/tasks" --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($taskList.tasks.Count -eq 7) 'GET /tasks lists the project tasks' "actual $($taskList.tasks.Count)"

$moveId = ($taskList.tasks | Where-Object { $_.kind -eq 'move' }).id
$patched = (& $cgw api PATCH "/api/projects/$projectId/tasks/$moveId" --body '{"name":"改名后的剪切"}' --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($patched.task.name -eq '改名后的剪切') 'PATCH changed name' "$patched"
# Key point: **only the given keys change**. The contract and template path must stay as they were,
# otherwise PATCH is just a disguised overwrite.
Expect ($patched.task.from.path -eq '{{inputs.source}}') 'PATCH left other fields alone (template path still there)' "$patched"
Expect ($patched.task.outputs.moved.required -eq $false) 'PATCH kept the outputs declaration' "$patched"

$rejected = (& $cgw api PATCH "/api/projects/$projectId/tasks/$moveId" --body '{"nope":1}' --url $url 2>&1 | Out-String)
Expect ($LASTEXITCODE -eq 3 -and $rejected -match 'unknownField') 'PATCH rejects unknown fields (exit code 3)' $rejected

$batchList = (& $cgw api GET "/api/projects/$projectId/batches" --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($batchList.batches.Count -eq 2) 'GET /batches lists batch workflows' "actual $($batchList.batches.Count)"
$flowId = ($batchList.batches | Where-Object { $_.name -eq '全流程' }).id
$patchedBatch = (& $cgw api PATCH "/api/projects/$projectId/batches/$flowId" --body '{"name":"全流程 v2"}' --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($patchedBatch.batch.name -eq '全流程 v2' -and $patchedBatch.batch.steps.Count -eq 2) 'PATCH batch changed only name, steps untouched' "$patchedBatch"

# ---------------------------------------------------------------- cross-project workflow templates (§14.3)
Write-Host "`n--- workflow templates ---"
$wfSchema = (& $cgw schema workflow --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($null -ne $wfSchema.properties.tasks -and $null -ne $wfSchema.properties.steps) 'workflow schema has tasks / steps'
# The embedded task definition is the same one as `schema task` (defined in definitions.TaskInput)
Expect ($wfSchema.definitions.TaskInput.properties.kind.enum.Count -eq 7) 'template tasks match `schema task` (seven kinds)' "$($wfSchema.definitions.PSObject.Properties.Name -join ',')"
Expect ($wfSchema.definitions.TaskInput.oneOf.Count -eq 7) 'embedded task definition has a required branch per kind'

$wfList = (& $cgw workflows --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$wfIds = @($wfList.workflows | ForEach-Object { $_.id })
Expect ($wfIds -contains 'push-build-pull' -and $wfIds -contains 'build-export-zip') 'both built-in templates are seeded on first start' ($wfIds -join ',')
Expect (@($wfList.workflows | Where-Object { $_.valid }).Count -eq $wfList.workflows.Count) 'all built-in templates are valid' ($wfList.workflows | ConvertTo-Json -Compress -Depth 6)

# apply **only previews by default**: nothing is written into the project
$preview = (& $cgw workflows apply $projectId push-build-pull --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($preview.applied -eq $false) 'apply without --apply only previews'
Expect ($preview.preview.tasks.Count -eq 3) 'preview listed 3 tasks' "$($preview.preview | ConvertTo-Json -Compress -Depth 4)"
Expect ($preview.preview.batchId -eq 'wf-push-build-pull') 'batch id is deterministic (repeated apply lands the same one)'
Expect (@($preview.conflicts).Count -eq 0) 'first apply has no conflicts'
$before = (& $cgw tasks $projectId --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect (@($before | Where-Object { $_.id -eq 't-push-source' }).Count -eq 0) 'preview wrote nothing into the project'

# Really write it: tasks + one batch workflow; a normal user can then run it directly
$applied = (& $cgw workflows apply $projectId push-build-pull --apply --set scheme=Runner --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($applied.applied -eq $true) 'apply wrote it in' "$applied"
$listed2 = (& $cgw tasks $projectId --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$installed = $listed2 | Where-Object { $_.id -eq 't-build-app' }
Expect ($installed.manifest -eq 'xcode') 'parameter manifest used the default' "$($installed | ConvertTo-Json -Compress)"
Expect ($installed.name -eq '构建 Runner (Release)') 'parameter scheme used the --set value' "$($installed.name)"
$wfBatches = (& $cgw batches $projectId --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$created = $wfBatches | Where-Object { $_.id -eq 'wf-push-build-pull' }
Expect ($created -and $created.steps.Count -eq 3 -and $created.steps[2].variables.source -eq '{{steps.build.outputs.app}}') 'the applied batch workflow carries a step output reference' "$($created | ConvertTo-Json -Compress -Depth 6)"

# Apply again: same name -> 409 workflowConflict (no guessing, the caller decides)
$again = & $cgw api POST "/api/projects/$projectId/workflows/push-build-pull/apply" --body '{"apply":true}' --url $url 2>&1 | Out-String
Expect ($LASTEXITCODE -ne 0 -and $again -match 'workflowConflict') 'name conflict reports workflowConflict (non-zero exit code)' "exit=$LASTEXITCODE $again"
$forced = (& $cgw workflows apply $projectId push-build-pull --apply --overwrite --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
Expect ($forced.applied -eq $true -and @($forced.conflicts).Count -eq 4) 'only --overwrite overwrites, listing all conflicts (3 tasks + 1 batch)' "$forced"

# A bad parameter must be reported, not silently ignored
$unknownVar = & $cgw workflows apply $projectId push-build-pull --apply --overwrite --set nope=1 --url $url 2>&1 | Out-String
Expect ($LASTEXITCODE -ne 0 -and $unknownVar -match '没有声明参数 nope') 'a value for an undeclared parameter is rejected' "exit=$LASTEXITCODE $unknownVar"

# What lands is a normal batch: a user can run it without AI (here only the id must be known)
$runIt = & $cgw batch run $projectId wf-push-build-pull --json --url $url 2>&1 | Out-String
Expect ($LASTEXITCODE -eq 0 -and $runIt -match 'jobId') 'the applied batch runs via plain `cgw batch run`' "exit=$LASTEXITCODE $runIt"

# ---------------------------------------------------------------- ajv (real documents)
Write-Host "`n--- ajv validates six schemas ---"
$env:CGW_URL = $url
Push-Location "$repo\mcp"
$nodeOut = (node test\schema.mjs 2>&1 | Out-String)
$nodeCode = $LASTEXITCODE
Pop-Location
# NOTE: these needles must track `mcp/test/schema.mjs`'s own output text ("all passed",
# "checks did not pass"). If that suite's wording changes, update them here too.
$nodeOut.Trim() -split "`r?`n" | Where-Object { $_ -match '^(---|  FAIL|all passed|[0-9]+ checks did not pass)' } | ForEach-Object { "  $_" }
Expect ($nodeCode -eq 0 -and $nodeOut -match 'all passed') 'ajv all passed' "exit=$nodeCode"
Expect ($nodeOut -match 'real tasks in the daemon must pass') 'ajv validated real tasks (seven kinds)'

# ---------------------------------------------------------------- first-build precheck
# Acceptance record §4.2: this project was never pushed (lastSyncAt = 0) and `build` does **not**
# auto-push. It used to just drop a remote `chmod: gradlew: No such file or directory`, looking
# like an environment problem; now the job log says it clearly up front and offers two right ways.
Write-Host "`n--- first-build precheck ---"
$run = (& $cgw run $projectId $byKind['build'] --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$jobId = $run.jobId
if (-not $jobId) { throw "no jobId: $run" }
$job = $null
for ($i = 0; $i -lt 40; $i++) {
  Start-Sleep -Milliseconds 250
  $job = (& $cgw job $jobId --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
  if ($job.state -ne 'running') { break }
}
Expect ($job.state -ne 'running') "build job finished (state $($job.state); an unreachable target is expected)" ''
$logs = (& $cgw jobs logs $jobId --json --url $url 2>&1 | Out-String) | ConvertFrom-Json
$text = (@($logs.entries) | ForEach-Object { $_.text }) -join "`n"
Expect ($text -match '还没推送过源码' -and $text -match '不会自动 push') 'says clearly that build does not auto-push (not just a remote error)' $text
Expect ($text -match 'push -> build 的 batch') 'and gives the recommended route (a push -> build batch)' ''

Stop-Process -Id $daemon.Id -Force -ErrorAction SilentlyContinue
if ($bad -gt 0) { Write-Host "`n$bad assertions failed" -ForegroundColor Red; exit 1 }
Write-Host "`nall passed" -ForegroundColor Green


