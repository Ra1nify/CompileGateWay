export type StringKey = keyof (typeof STRINGS)["zh-Hans"];

/** Anything other than status.language (early boot, failed request) falls back to en-US. */
export function normalizeLanguage(value: string | null | undefined): Language {
  return value === "zh-Hans" ? "zh-Hans" : "en-US";
}

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

/** Replace {name} placeholders the way the old UI did. */
export function makeT(language: Language): Translate {
  const table = STRINGS[language] ?? STRINGS["en-US"];
  return (key, vars) => {
    let text: string = table[key] ?? STRINGS["en-US"][key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}






